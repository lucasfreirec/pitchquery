"""Benchmark the language pipeline and end-to-end queries; writes docs/performance.md.

    make bench        (or: uv run python benchmarks/bench.py)

Needs the dataset (`make data`). Each timing is the median of many runs after a warm-up.
"""

import platform
import statistics
import time
from collections.abc import Callable
from datetime import date
from pathlib import Path

import duckdb

from pitchquery.data.paths import DataPaths
from pitchquery.data.values import ValueIndex, load_value_index
from pitchquery.engine import Engine
from pitchquery.lang.analyzer import check
from pitchquery.lang.compiler import compile_query
from pitchquery.lang.parser import parse

OUT = Path(__file__).resolve().parents[2] / "docs" / "performance.md"

QUERIES = [
    "shots",
    'shots where xg > 0.3 and team = "Argentina" and minute >= 80',
    'passes where player = "Lionel Messi" and outcome = "complete" and end_x > 102',
    'events where type in ("Shot", "Dribble") and under_pressure = true',
    'shots where team = "France" | count by player | sort desc | limit 5',
    "events | count by player | sort desc | limit 10",
    'events where player contains "messi" | sort desc minute | limit 100',
    'shots where player = "Mbape"',  # unknown value: exercises "did you mean" over all players
]


def median_us(fn: Callable[[], object], runs: int) -> float:
    fn()  # warm-up
    samples = []
    for _ in range(runs):
        start = time.perf_counter()
        fn()
        samples.append((time.perf_counter() - start) * 1e6)
    return statistics.median(samples)


def bench_language(values: ValueIndex) -> list[tuple[str, float, float, float]]:
    rows = []
    for source in QUERIES:
        query = parse(source)
        parse_us = median_us(lambda s=source: parse(s), 500)  # type: ignore[misc]
        check_us = median_us(lambda s=source: check(s, values), 100)  # type: ignore[misc]
        compile_us = median_us(lambda q=query: compile_query(q), 500)  # type: ignore[misc]
        rows.append((source, parse_us, check_us, compile_us))
    return rows


def bench_engine(engine: Engine) -> list[tuple[str, float, int]]:
    rows = []
    for source in QUERIES:
        result = engine.run(source)
        ms = median_us(lambda s=source: engine.run(s), 20) / 1000  # type: ignore[misc]
        rows.append((source, ms, len(result.rows)))
    return rows


def cell(query: str) -> str:
    # A `|` splits a markdown table cell even inside backticks.
    return "`" + query.replace("|", "\\|") + "`"


def main() -> None:
    paths = DataPaths.default()
    values = load_value_index(paths.values_json)

    start = time.perf_counter()
    engine = Engine(paths.events_parquet, values)
    load_ms = (time.perf_counter() - start) * 1000
    total_events = engine.execute_sql("SELECT count(*) FROM events", ())[1][0][0]

    language = bench_language(values)
    end_to_end = bench_engine(engine)
    engine.close()

    lines = [
        "# Performance",
        "",
        "Generated by `make bench` (`backend/benchmarks/bench.py`). Medians after a warm-up.",
        "",
        f"- Date: {date.today().isoformat()}",
        f"- Machine: {platform.machine()}, {platform.system()} {platform.release()}",
        f"- Python {platform.python_version()}, DuckDB {duckdb.__version__}",
        f"- Dataset: {total_events:,} events; loaded into memory in {load_ms:.0f} ms",
        "",
        "## Language pipeline",
        "",
        "`check` = parse + semantic analysis against the schema and the value index.",
        "",
        "| Query | parse (µs) | check (µs) | compile (µs) |",
        "|-------|-----------:|-----------:|-------------:|",
        *(f"| {cell(q)} | {p:.0f} | {c:.0f} | {k:.0f} |" for q, p, c, k in language),
        "",
        "## End to end",
        "",
        "`Engine.run`: check + compile + execute on DuckDB + fetch (row cap 5,000).",
        "",
        "| Query | time (ms) | rows |",
        "|-------|----------:|-----:|",
        *(f"| {cell(q)} | {ms:.1f} | {n:,} |" for q, ms, n in end_to_end),
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
